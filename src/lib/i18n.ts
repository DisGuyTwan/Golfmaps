/** Acres, formatted for the language: "12.34" / "12,34". */
export function formatAcres(acres: number, lang: Lang): string {
  return acres.toLocaleString(lang === "fr" ? "fr-CA" : "en-CA", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
}
